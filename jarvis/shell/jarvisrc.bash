# J.A.R.V.I.S. terminal profile: loads your normal bash setup, then adds the HUD prompt.
[ -f /etc/profile ] && . /etc/profile
[ -f "$HOME/.bashrc" ] && . "$HOME/.bashrc"

# accent colour (r;g;b) and theme (jarvis | celestia | doom | asahina) from the HUD; the app keeps the current
# pair in $JARVIS_STYLE_FILE so open tabs follow theme changes
_J_C="${JARVIS_ACCENT:-0;225;255}"
_J_SKIN="${JARVIS_SKIN:-jarvis}"
_j_c() { printf '\001\e[38;2;%sm\002' "$_J_C"; }
_J_DIM='\[\e[38;5;245m\]'
_J_ERR='\[\e[38;2;255;77;99m\]'
_J_R='\[\e[0m\]'
_J_RC="${BASH_SOURCE[0]}"
_J_ART_DIR="$(dirname "$_J_RC")"

# prompt label, marks and colours for the current theme
_j_apply_skin() {
  if [ "$_J_SKIN" = celestia ]; then
    _J_LABEL="♠ CELESTIA"; _J_OKMARK="♦"; _J_ARROW="❧"
    _J_OK='\[\e[38;2;217;180;108m\]'
  elif [ "$_J_SKIN" = asahina ]; then
    _J_LABEL="≈ HINA"; _J_OKMARK="★"; _J_ARROW="»"
    _J_OK='\[\e[38;2;205;220;57m\]'
  elif [ "$_J_SKIN" = doom ]; then
    _J_LABEL="D.O.O.M."; _J_OKMARK="■"; _J_ARROW=">"
    _J_OK='\[\e[38;2;170;255;190m\]'
  else
    _J_LABEL="J.A.R.V.I.S."; _J_OKMARK="◆"; _J_ARROW="❯"
    _J_OK='\[\e[38;2;61;255;181m\]'
  fi
}

_j_banner() {
  local c=$'\e[38;2;'"$_J_C"'m' d=$'\e[38;5;245m' b=$'\e[1m' r=$'\e[0m'
  local info="${HOSTNAME} · $(uname -r) · $(uptime -p 2>/dev/null | sed 's/^up //')" when
  when="$(date '+%A %d %B · %H:%M')"
  if [ "$_J_SKIN" = doom ] && [ -r "$_J_ART_DIR/doom.ans" ]; then
    # Doom's mask (pixel art shared with the HUD, generated by make_pixel_art.py) and a status readout
    local i=0 line
    local cap=("" "" "" "" \
      "${c}${b}D . O . O . M .${r}" \
      "${c}DIGITAL OVERLORD OPERATIONS MAINFRAME${r}" \
      "${d}LATVERIAN EMBASSY NET · SECURE LINK ESTABLISHED${r}" \
      "" \
      "${d}NODE   ${r}${c}${info}${r}" \
      "${d}CLOCK  ${r}${c}${when}${r}" \
      "${d}ACCESS ${r}${c}SOVEREIGN${r}" \
      "" \
      "${c}> DOOM DOES NOT ASK. DOOM COMMANDS.${r}")
    while IFS= read -r line; do
      printf '  %s   %s\n' "$line" "${cap[i]}"
      i=$((i + 1))
    done < "$_J_ART_DIR/doom.ans"
  elif [ "$_J_SKIN" = celestia ] && [ -r "$_J_ART_DIR/celestia.ans" ]; then
    # 8-bit Celestia (generated by make_pixel_art.py) with the caption beside her
    local g=$'\e[38;2;217;180;108m' i=0 line
    local cap=("" "" "" "" \
      "${g}${b}C E L E S T I A   L U D E N B E R G${r}" \
      "${c}THE ULTIMATE GAMBLER · SECURE SHELL${r}" \
      "" \
      "${d}${info}${r}" \
      "${d}${when}${r}" \
      "" \
      "${c}♠ ♥ ♦ ♣${r}  ${g}The house always wins.${r}")
    while IFS= read -r line; do
      printf '  %s   %s\n' "$line" "${cap[i]}"
      i=$((i + 1))
    done < "$_J_ART_DIR/celestia.ans"
  elif [ "$_J_SKIN" = asahina ] && [ -r "$_J_ART_DIR/asahina.ans" ]; then
    # 8-bit Hina (generated by make_pixel_art.py from reference/AoiReference.png) with a caption
    local a=$'\e[38;2;64;200;255m' y=$'\e[38;2;205;220;57m' i=0 line
    local cap=("" "" "" "" \
      "${c}${b}A O I   A S A H I N A${r}" \
      "${a}THE ULTIMATE SWIMMING PRO · POOL DECK SHELL${r}" \
      "" \
      "${d}${info}${r}" \
      "${d}${when}${r}" \
      "" \
      "${a}≈≈≈≈${r}  ${y}Let's give it everything we've got!${r}")
    while IFS= read -r line; do
      printf '  %s   %s\n' "$line" "${cap[i]}"
      i=$((i + 1))
    done < "$_J_ART_DIR/asahina.ans"
  else
    printf '%s\n' \
      "${c}    ╭──────╮${r}" \
      "${c}  ╭─┤ ╭──╮ ├─╮   ${b}J . A . R . V . I . S .${r}" \
      "${c}  │ │ │◉◉│ │ │   ${r}${c}SECURE SHELL INTERFACE${r}" \
      "${c}  ╰─┤ ╰──╯ ├─╯   ${d}${info}${r}" \
      "${c}    ╰──────╯${r}     ${d}${when}${r}"
  fi
}

# pick up a theme change from the HUD; a new theme restarts the shell (same pid, cwd and exported
# env) on a cleared screen, so fastfetch and the new banner show without the old one above them
_j_load_style() {
  [ -n "$JARVIS_STYLE_FILE" ] && [ -r "$JARVIS_STYLE_FILE" ] || return
  local skin accent
  read -r skin accent < "$JARVIS_STYLE_FILE" || return
  [ -n "$accent" ] && _J_C="$accent"
  if [ -n "$skin" ] && [ "$skin" != "$_J_SKIN" ]; then
    history -a
    printf '\e[H\e[2J\e[3J'
    JARVIS_SKIN="$skin" JARVIS_ACCENT="$_J_C" exec "$BASH" --rcfile "$_J_RC" -i
    # exec failed: fall back to redrawing in this shell
    _J_SKIN="$skin"; _j_apply_skin; _j_banner
  fi
}

_jarvis_prompt() {
  local st=$?
  _j_load_style
  local mark="${_J_OK}${_J_OKMARK}${_J_R}"
  (( st != 0 )) && mark="${_J_ERR}✕ ${st}${_J_R}"
  local branch=""
  if command -v git >/dev/null 2>&1; then
    branch=$(git symbolic-ref --short HEAD 2>/dev/null || git rev-parse --short HEAD 2>/dev/null)
    [ -n "$branch" ] && branch=" ${_J_DIM}⎇ ${branch}${_J_R}"
  fi
  local venv=""
  [ -n "$VIRTUAL_ENV" ] && venv=" ${_J_DIM}($(basename "$VIRTUAL_ENV"))${_J_R}"
  PS1="\n\[$(_j_c)\]╭─[\[\e[1m\]${_J_LABEL}\[\e[22m\]]${_J_R} ${_J_DIM}\u@\h${_J_R} \[$(_j_c)\]\w${_J_R}${branch}${venv} ${mark}\n\[$(_j_c)\]╰─${_J_ARROW}${_J_R} "
  return $st
}
PROMPT_COMMAND="_jarvis_prompt${PROMPT_COMMAND:+; $PROMPT_COMMAND}"

# The app types \e[9998~ into a shell idle at its prompt when the theme changes: stash whatever
# was typed (into history, so Up brings it back) and accept the empty line, which redraws the
# prompt, which restarts the shell in the new theme. Readline would otherwise keep showing the old prompt.
_j_stash() {
  [ -n "$READLINE_LINE" ] && history -s -- "$READLINE_LINE"
  READLINE_LINE=""; READLINE_POINT=0
}
if [[ $- == *i* ]]; then
  bind -x '"\e[9999~": _j_stash' 2>/dev/null
  bind '"\e[9998~": "\e[9999~\C-m"' 2>/dev/null
fi

_j_apply_skin
[ -z "$JARVIS_NO_BANNER" ] && _j_banner
unset JARVIS_NO_BANNER
